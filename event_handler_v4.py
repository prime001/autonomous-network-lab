"""Device Event Handler – Run ad‑hoc commands on network devices via SSH.

This utility lets a network engineer execute a single command (e.g., *show
bgp summary*, *show interfaces status*) on a remote network device over SSH,
capture the output, optionally convert it to JSON and store the result in a
log file.

Typical usage::

    python device_event_handler.py \\
        --host 10.0.0.1 \\
        --username admin \\
        --command "show ip interface brief" \\
        --output results.json

Prerequisites
-------------
* Python 3.8+ (uses ``subprocess`` and ``argparse`` from the standard library)
* An SSH client available on the execution host (the script calls the system
  ``ssh`` binary)
* Network device must permit SSH access with the supplied credentials
* For password‑less operation, provide ``--ssh-key`` pointing to a private key
  file or ensure the key is loaded into the SSH agent

The script avoids external libraries (e.g., paramiko, netmiko) to stay fully
portable and lightweight while still offering useful error handling and
logging.
"""

import argparse
import json
import logging
import shlex
import subprocess
import sys
import getpass
from pathlib import Path
from typing import List, Optional

# --------------------------------------------------------------------------- #
# Logging configuration
# --------------------------------------------------------------------------- #
LOGGER = logging.getLogger(__name__)
LOGGER.setLevel(logging.DEBUG)

_console_handler = logging.StreamHandler()
_console_handler.setLevel(logging.INFO)

_formatter = logging.Formatter(
    "%(asctime)s - %(name)s - %(levelname)s - %(message)s"
)
_console_handler.setFormatter(_formatter)
LOGGER.addHandler(_console_handler)


# --------------------------------------------------------------------------- #
# Helper functions
# --------------------------------------------------------------------------- #
def build_ssh_command(
    host: str,
    username: str,
    command: str,
    port: int = 22,
    ssh_key: Optional[Path] = None,
    timeout: int = 30,
) -> List[str]:
    """Construct the ``ssh`` command line.

    Args:
        host: Destination hostname or IP address.
        username: SSH username.
        command: Remote command to execute.
        port: SSH port (default 22).
        ssh_key: Path to a private key file (optional).
        timeout: Connection timeout in seconds.

    Returns:
        List of command arguments suitable for ``subprocess.run``.
    """
    ssh_base = [
        "ssh",
        "-o", "BatchMode=yes",
        "-o", f"ConnectTimeout={timeout}",
        "-p", str(port),
    ]

    if ssh_key:
        ssh_base.extend(["-i", str(ssh_key)])

    remote = f"{username}@{host}"
    ssh_base.append(remote)

    # Ensure the remote command is passed as a single argument
    ssh_base.append(command)

    LOGGER.debug("SSH command built: %s", " ".join(shlex.quote(arg) for arg in ssh_base))
    return ssh_base


def run_ssh_command(
    ssh_cmd: List[str],
    capture_stderr: bool = True,
) -> subprocess.CompletedProcess:
    """Execute the SSH command and capture its output.

    Args:
        ssh_cmd: List generated by :func:`build_ssh_command`.
        capture_stderr: Whether to capture stderr (default True).

    Returns:
        CompletedProcess instance containing stdout, stderr and returncode.

    Raises:
        RuntimeError: If the SSH command exits with a non‑zero status.
    """
    try:
        result = subprocess.run(
            ssh_cmd,
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            msg = (
                f"SSH command failed (rc={result.returncode}). "
                f"Stderr: {result.stderr.strip()}"
            )
            raise RuntimeError(msg)
        LOGGER.debug("SSH command succeeded. Stdout captured.")
        return result
    except FileNotFoundError as exc:
        raise RuntimeError(
            "SSH client not found. Ensure the 'ssh' binary is installed and in PATH."
        ) from exc
    except subprocess.SubprocessError as exc:
        raise RuntimeError("Failed to execute SSH command.") from exc


def parse_command_output(command: str, output: str) -> dict:
    """Very light weight parser that returns raw output; placeholder for real parsing.

    This function can be extended to convert device‑specific CLI output to structured
    JSON. For now it returns the raw text under a ``raw`` key and includes the command
    that generated it.

    Args:
        command: The command that was executed.
        output: Raw string output from the device.

    Returns:
        Dictionary ready for JSON serialization.
    """
    return {
        "command": command,
        "output": output.strip(),
    }


def write_output(data: dict, path: Path) -> None:
    """Write JSON data to ``path`` with pretty formatting.

    Args:
        data: Dictionary to serialize.
        path: Destination file path.
    """
    try:
        with path.open("w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        LOGGER.info("Result written to %s", path)
    except OSError as exc:
        raise RuntimeError(f"Unable to write to {path}: {exc}") from exc


# --------------------------------------------------------------------------- #
# Main execution logic
# --------------------------------------------------------------------------- #
def main() -> None:
    parser = argparse.ArgumentParser(
        description="Execute a single command on a network device via SSH."
    )
    parser.add_argument(
        "--host",
        required=True,
        help="Hostname or IP address of the target device.",
    )
    parser.add_argument(
        "--username",
        required=True,
        help="SSH username to connect with.",
    )
    parser.add_argument(
        "--password",
        required=False,
        help="SSH password (will prompt if omitted and no key provided).",
    )
    parser.add_argument(
        "--ssh-key",
        type=Path,
        required=False,
        help="Path to an SSH private key for key‑based authentication.",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=22,
        help="TCP port for SSH (default: 22).",
    )
    parser.add_argument(
        "--command",
        required=True,
        help="Command to run on the remote device (quoted if it contains spaces).",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=30,
        help="SSH connection timeout in seconds (default: 30).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=False,
        help="Path to JSON file where the result will be saved.",
    )
    parser.add_argument(
        "--log-file",
        type=Path,
        required=False,
        help="Write detailed logs to the given file.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show the constructed SSH command without executing it.",
    )

    args = parser.parse_args()

    # Configure file logging if requested
    if args.log_file:
        file_handler = logging.FileHandler(args.log_file, encoding="utf-8")
        file_handler.setLevel(logging.DEBUG)
        file_handler.setFormatter(_formatter)
        LOGGER.addHandler(file_handler)
        LOGGER.info("File logging enabled: %s", args.log_file)

    # Resolve password handling
    password = args.password
    if not password and not args.ssh_key:
        # Prompt securely
        password = getpass.getpass(prompt="SSH password: ")

    # Build the remote command string.
    # If a password is needed, we inject it via sshpass (fallback to ssh if sshpass unavailable)
    remote_cmd = args.command

    if password and not args.ssh_key:
        # Prefer sshpass to avoid interactive password prompt
        if shutil.which("sshpass"):
            ssh_cmd = [
                "sshpass",
                "-p",
                password,
            ] + build_ssh_command(
                host=args.host,
                username=args.username,
                command=remote_cmd,
                port=args.port,
                ssh_key=args.ssh_key,
                timeout=args.timeout,
            )
        else:
            LOGGER.warning(
                "sshpass not found; falling back to interactive SSH. Provide a key for automation."
            )
            ssh_cmd = build_ssh_command(
                host=args.host,
                username=args.username,
                command=remote_cmd,
                port=args.port,
                ssh_key=args.ssh_key,
                timeout=args.timeout,
            )
    else:
        ssh_cmd = build_ssh_command(
            host=args.host,
            username=args.username,
            command=remote_cmd,
            port=args.port,
            ssh_key=args.ssh_key,
            timeout=args.timeout,
        )

    if args.dry_run:
        LOGGER.info("Dry‑run mode – SSH command that would be executed:")
        LOGGER.info(" ".join(shlex.quote(part) for part in ssh_cmd))
        sys.exit(0)

    # Execute the SSH command
    try:
        result = run_ssh_command(ssh_cmd)
    except RuntimeError as exc:
        LOGGER.error("Execution failed: %s", exc)
        sys.exit(1)

    # Parse and optionally save output
    parsed = parse_command_output(args.command, result.stdout)
    if args.output:
        try:
            write_output(parsed, args.output)
        except RuntimeError as exc:
            LOGGER.error("%s", exc)
            sys.exit(1)
    else:
        # Print to stdout in a readable format
        print(json.dumps(parsed, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()